import XCTest
@testable import StashCore

final class KDFVectorTests: XCTestCase {

    /// Известный вектор PBKDF2-HMAC-SHA256 из RFC 7914, §11:
    /// P="passwd", S="salt", c=1, dkLen=64.
    func testPBKDF2SHA256KnownVector() throws {
        let params = KDFParameters(algorithm: .pbkdf2HMACSHA256,
                                   iterations: 1,
                                   salt: Data("salt".utf8))
        let key = try KDF.derive(password: Data("passwd".utf8), parameters: params, keyLength: 64)
        let got = key.withUnsafeBytes { Data($0) }
        let expected = Data([
            0x55, 0xac, 0x04, 0x6e, 0x56, 0xe3, 0x08, 0x9f,
            0xec, 0x16, 0x91, 0xc2, 0x25, 0x44, 0xb6, 0x05,
            0xf9, 0x41, 0x85, 0x21, 0x6d, 0xde, 0x04, 0x65,
            0xe6, 0x8b, 0x9d, 0x57, 0xc2, 0x0d, 0xac, 0xbc,
            0x49, 0xca, 0x9c, 0xcc, 0xf1, 0x79, 0xb6, 0x45,
            0x99, 0x16, 0x64, 0xb3, 0x9d, 0x77, 0xef, 0x31,
            0x7c, 0x71, 0xb8, 0x45, 0xb1, 0xe3, 0x0b, 0xd5,
            0x09, 0x11, 0x20, 0x41, 0xd3, 0xa1, 0x97, 0x83,
        ])
        XCTAssertEqual(got, expected)
    }
}
